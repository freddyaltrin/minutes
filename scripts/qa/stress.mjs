import { join } from 'node:path'
export default async function (win, app, out) {
  const shot = (n) => win.screenshot({ path: join(out, n) })
  const t0 = Date.now()
  await win.evaluate(async () => {
    const words = 'pipeline review budget client proposal drawings schedule invoice design approval tracker site survey'.split(' ')
    for (let i = 0; i < 300; i++) {
      const body = Array.from({ length: 40 }, (_, k) => words[(i + k) % words.length]).join(' ')
      await window.minutes.notes.create({ title: `Meeting ${i} with ${words[i % words.length]}`, bodyText: body, bodyJson: JSON.stringify({ type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: body }] }] }), meetingAt: Date.now() - i * 3600_000 * 7, attendees: ['Deepak Anand', 'Sam', 'Vetri'] })
    }
    // one very long note (~20k words)
    const long = Array.from({ length: 800 }, (_, k) => ({ type: 'paragraph', content: [{ type: 'text', text: `Paragraph ${k}: ` + words.join(' ') + ' ' + words.join(' ') }] }))
    await window.minutes.notes.create({ title: 'Very long note', bodyText: long.map((p) => p.content[0].text).join('\n'), bodyJson: JSON.stringify({ type: 'doc', content: long }) })
  })
  console.log('seeded 301 notes in', Date.now() - t0, 'ms')
  await win.click('text=All notes')
  await win.waitForTimeout(800)
  const t1 = Date.now()
  await win.click('text=Very long note')
  await win.waitForTimeout(500)
  console.log('open long note', Date.now() - t1, 'ms')
  await win.click('.ProseMirror')
  await win.keyboard.press('Control+End')
  const t2 = Date.now()
  await win.keyboard.type('Typing at the end of a very long note should stay responsive. '.repeat(3))
  console.log('typed 190 chars in', Date.now() - t2, 'ms')
  await win.waitForTimeout(1200)
  await shot('40-long-note.png')
  const t3 = Date.now()
  const res = await win.evaluate(() => window.minutes.search.query('invoice tracker', { scope: 'all' }, 60))
  console.log('search over 301 notes:', res.total, 'hits in', res.tookMs, 'ms (ipc total', Date.now() - t3, 'ms)')
  await win.setViewportSize({ width: 760, height: 520 })
  await win.waitForTimeout(400)
  await shot('41-small-window.png')
  await win.setViewportSize({ width: 1180, height: 760 })
  await win.click('text=All notes')
  await win.waitForTimeout(400)
  await shot('42-list-300.png')
}
