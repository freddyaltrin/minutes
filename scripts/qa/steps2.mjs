import { join } from 'node:path'
export default async function (win, app, out) {
  const shot = (n) => win.screenshot({ path: join(out, n) })
  await shot('11-welcome.png')
  await win.keyboard.press('Control+N')
  await win.waitForTimeout(400)
  await win.fill('textarea[aria-label="Note title"]', 'Weekly standup with the engineering leads')
  await win.click('.ProseMirror')
  await win.keyboard.type('Who owns the FST as-built review? Vetri will schedule the client call next Tuesday.\n')
  await win.waitForTimeout(1000)
  await win.keyboard.press('Control+T')
  await win.waitForTimeout(400)
  const input = await win.$('input[type=file]')
  await input.setInputFiles({ name: 'meeting.srt', mimeType: 'text/plain', buffer: Buffer.from('1\n00:00:01,000 --> 00:00:04,000\nFredrick: Let us start with the FST as-built status.\n\n2\n00:00:05,000 --> 00:00:09,500\nVetri: The RLM comparison is done. We need to send the invoice by the 25th of October.\n\n3\n00:00:10,000 --> 00:00:14,000\nDeepak: Agreed, let\'s go ahead with Rev-3 as the basis.\n\n4\n00:00:15,000 --> 00:00:19,000\nFredrick: Can you share the tracker with Petroka tomorrow?\n') })
  await win.waitForTimeout(800)
  await shot('12-transcript-narrow.png')
  await win.click('button[aria-label="Suggestions"]')
  await win.waitForTimeout(900)
  await shot('13-suggestions.png')
  await win.keyboard.press('Control+J')
  await win.waitForTimeout(300)
  await win.keyboard.type('what deadlines were mentioned?')
  await win.waitForTimeout(600)
  await shot('14-ask.png')
  await win.keyboard.press('Escape')
  await win.keyboard.press('Control+,')
  await win.waitForTimeout(400)
  await win.click('button:has-text("Dark")')
  await win.waitForTimeout(300)
  await win.click('text=Transcription')
  await win.waitForTimeout(400)
  await shot('15-settings-transcription-dark.png')
  await win.click('text=Shortcuts')
  await win.waitForTimeout(300)
  await shot('16-shortcuts.png')
  await win.keyboard.press('Escape')
  await win.click('button[aria-label="Suggestions"]')
  await win.waitForTimeout(300)
  await win.setViewportSize({ width: 1400, height: 860 })
  await win.keyboard.press('Control+T')
  await win.waitForTimeout(500)
  await shot('17-dark-wide.png')
  await win.click('button[aria-label="More"]')
  await win.waitForTimeout(300)
  await shot('18-menu.png')
  await win.keyboard.press('Escape')
  await win.click('button[aria-label="Record"]').catch(()=>{})
  await win.waitForTimeout(600)
  await shot('19-record-dialog.png')
}
